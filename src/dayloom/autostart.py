"""Start the daemon automatically at logon.

Two mechanisms exist on Windows and they have very different permission
stories:

* **Task Scheduler** with an ``ONLOGON`` trigger is the robust option (it can be
  delayed, and it survives shell changes), but creating one requires an elevated
  token. A normal, UAC-non-elevated process gets ``ERROR: Access is denied``.
* **The per-user Startup folder** needs no elevation at all, shows up as a
  normal shortcut the user can delete, and is what most desktop tools use.

So dayloom defaults to the Startup folder, creating a ``.lnk`` that launches
``pythonw.exe`` (no console window). The scheduler path stays available behind
``prefer_scheduler=True`` for people who run it elevated and want the extra
guarantees.
"""

from __future__ import annotations

import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

from .shortcuts import pythonw as launcher

TASK_NAME = "dayloom"
SHORTCUT_NAME = "dayloom.lnk"
FALLBACK_NAME = "dayloom.cmd"
CREATE_NO_WINDOW = 0x08000000


@dataclass(slots=True)
class AutostartStatus:
    registered: bool
    method: str = ""  # "startup" | "scheduler"
    command: str = ""
    detail: str = ""


# ----------------------------------------------------------------------
# paths
# ----------------------------------------------------------------------
def startup_dir() -> Path:
    appdata = os.environ.get("APPDATA")
    base = Path(appdata) if appdata else Path.home() / "AppData" / "Roaming"
    return base / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"


def shortcut_path() -> Path:
    return startup_dir() / SHORTCUT_NAME


def fallback_path() -> Path:
    return startup_dir() / FALLBACK_NAME


def cli_command(*args: str, config_path: Path | None = None) -> list[str]:
    """A CLI invocation that works in both layouts.

    Frozen: the GUI exe cannot run subcommands (it has no console), so the
    sibling console exe must be used — ``sys.executable`` here would relaunch
    the GUI and hit the single-instance lock.
    """
    if getattr(sys, "frozen", False):
        exe = Path(sys.executable)
        console = exe.with_name("dayloom.exe")
        command = [str(console if console.exists() else exe), *args]
    else:
        command = [launcher(), "-m", "dayloom", *args]
    if config_path is not None:
        command += ["--config", str(config_path)]
    return command


def build_command(config_path: Path | None = None) -> list[str]:
    """Command that runs the daemon, in dev (pythonw) and frozen (exe) layouts."""
    return cli_command("start", config_path=config_path)


def gui_command(config_path: Path | None = None) -> list[str]:
    """Command that opens the desktop client (windowed: no console at logon)."""
    from .shortcuts import gui_command as shortcut_command

    command = shortcut_command()
    if config_path is not None:
        command += ["--config", str(config_path)]
    return command


# ----------------------------------------------------------------------
# startup folder
# ----------------------------------------------------------------------
def _write_cmd(command: list[str]) -> None:
    """Last-resort launcher: a .cmd next to the shortcut."""
    line = subprocess.list2cmdline(command)
    fallback_path().write_text(
        "@echo off\r\n"
        "rem generated by `dayloom autostart enable`\r\n"
        f"start \"\" {line}\r\n"
        "exit /b 0\r\n",
        encoding="utf-8",
    )


def enable_startup(
    config_path: Path | None = None, *, gui: bool = True
) -> tuple[bool, str]:
    directories = startup_dir()
    try:
        directories.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        return False, f"无法访问启动文件夹：{exc}"

    target = shortcut_path()
    target.unlink(missing_ok=True)
    command = gui_command(config_path) if gui else build_command(config_path)
    arguments = subprocess.list2cmdline(command[1:])
    from .shortcuts import create_shortcut, icon_location

    label = "打开界面" if gui else "后台采集"
    if create_shortcut(
        target,
        target=command[0],
        arguments=arguments,
        workdir=Path.home(),
        icon=icon_location(),
        description=f"dayloom — 开机{label}",
    ):
        fallback_path().unlink(missing_ok=True)
        return True, f"已加入开机自启（{label}）：{target}"

    try:
        _write_cmd(command)
    except OSError as exc:
        return False, f"写入启动脚本失败：{exc}"
    return True, f"已加入开机自启（启动脚本，登录时可能闪过一次黑窗）：{fallback_path()}"


# ----------------------------------------------------------------------
# task scheduler (optional, needs elevation)
# ----------------------------------------------------------------------
def _run(args: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        args,
        capture_output=True,
        text=True,
        encoding="oem",
        errors="replace",
        timeout=30,
        creationflags=CREATE_NO_WINDOW,
    )


def enable_scheduler(
    config_path: Path | None = None, task_name: str = TASK_NAME, *, gui: bool = True
) -> tuple[bool, str]:
    command = gui_command(config_path) if gui else build_command(config_path)
    try:
        proc = _run(
            [
                "schtasks",
                "/Create",
                "/TN",
                task_name,
                "/TR",
                subprocess.list2cmdline(command),
                "/SC",
                "ONLOGON",
                "/RL",
                "LIMITED",
                "/F",
            ]
        )
    except (OSError, subprocess.SubprocessError) as exc:
        return False, f"调用 schtasks 失败：{exc}"
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or "").strip().replace("\r\n", " ")
        return False, f"创建计划任务失败（ONLOGON 需要管理员权限）：{detail[:200]}"
    return True, "已通过任务计划程序加入开机自启"


def scheduler_status(task_name: str = TASK_NAME) -> AutostartStatus:
    try:
        proc = _run(["schtasks", "/Query", "/TN", task_name, "/FO", "LIST", "/V"])
    except (OSError, subprocess.SubprocessError):
        return AutostartStatus(False)
    if proc.returncode != 0:
        return AutostartStatus(False)
    command = ""
    for line in (proc.stdout or "").splitlines():
        if "Task To Run" in line or "要运行的任务" in line:
            command = line.split(":", 1)[-1].strip()
            break
    return AutostartStatus(True, method="scheduler", command=command, detail="计划任务")


# ----------------------------------------------------------------------
# public API
# ----------------------------------------------------------------------
def status() -> AutostartStatus:
    scheduled = scheduler_status()
    if scheduled.registered:
        return scheduled
    for path, method in ((shortcut_path(), "startup"), (fallback_path(), "startup")):
        if path.exists():
            return AutostartStatus(True, method=method, command=str(path), detail="启动文件夹")
    return AutostartStatus(False, detail="未开启")


def enable(
    config_path: Path | None = None, *, prefer_scheduler: bool = False, gui: bool = True
) -> tuple[bool, str]:
    """Register logon startup.

    ``gui=True`` (the default) opens the desktop client at logon: the client
    then starts the capture daemon itself, so logging in shows a window and
    starts recording. ``gui=False`` keeps the old headless behaviour (daemon
    only), which is what you want on a machine nobody looks at.
    """
    if prefer_scheduler:
        ok, message = enable_scheduler(config_path, gui=gui)
        if ok:
            return True, message
        ok, startup_message = enable_startup(config_path, gui=gui)
        if ok:
            return True, f"{message}；已改用启动文件夹。{startup_message}"
        return False, f"{message}；{startup_message}"
    return enable_startup(config_path, gui=gui)


def disable() -> tuple[bool, str]:
    removed: list[str] = []
    try:
        proc = _run(["schtasks", "/Delete", "/TN", TASK_NAME, "/F"])
        if proc.returncode == 0:
            removed.append("计划任务")
    except (OSError, subprocess.SubprocessError):
        pass
    for path in (shortcut_path(), fallback_path()):
        if path.exists():
            try:
                path.unlink()
                removed.append(path.name)
            except OSError:
                pass
    if not removed:
        return True, "本来就没有开启开机自启"
    return True, "已取消开机自启（" + "、".join(removed) + "）"


def spawn_daemon(config_path: Path | None = None) -> bool:
    """Start the daemon detached from the calling process (no console window)."""
    command = build_command(config_path)
    flags = 0x00000008 | 0x00000200  # DETACHED_PROCESS | CREATE_NEW_PROCESS_GROUP
    try:
        subprocess.Popen(
            command,
            creationflags=flags,
            close_fds=True,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        return True
    except OSError:
        return False


def describe(config_path: Path | None = None) -> str:
    state = status()
    gui_line = subprocess.list2cmdline(gui_command(config_path))
    daemon_line = subprocess.list2cmdline(build_command(config_path))
    if state.registered:
        where = "任务计划程序" if state.method == "scheduler" else "启动文件夹"
        from .shortcuts import read_shortcut

        target, arguments = read_shortcut(shortcut_path())
        actual = f"{target} {arguments}".strip() if target else "（未读取到）"
        return (
            f"开机自启：已开启（{where}）\n"
            f"  位置：{state.command or '（未读取到）'}\n"
            f"  实际运行：{actual}\n"
            f"  界面版：{gui_line}\n"
            f"  仅采集：{daemon_line}\n"
            "  关闭：dayloom autostart disable"
        )
    return (
        "开机自启：未开启\n"
        "  开启：dayloom autostart enable            # 开机打开界面\n"
        "  或：  dayloom autostart enable --daemon   # 只开后台采集，不弹窗\n"
        "  （默认放一个快捷方式到启动文件夹，不需要管理员权限）\n"
        f"  位置：{shortcut_path()}"
    )
